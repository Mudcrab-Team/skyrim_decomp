#!/usr/bin/env python3
"""Derive public contributor credit from the current accepted inventory and its reports."""
from collections import defaultdict
from html import escape
import json
from pathlib import Path
import re

import build_model_trend as attribution

ROOT = Path(__file__).resolve().parents[1]
HANDLE = re.compile(r'@?([A-Za-z0-9](?:[A-Za-z0-9-]{0,37}[A-Za-z0-9])?)\Z')


def handle(value):
    match = HANDLE.fullmatch(value) if isinstance(value, str) else None
    return match[1].lower() if match else None


def credit(fn, record, root):
    # p161 records independent submissions, including alternate source digests. Deduplicate
    # below by contributor and function, not by submission, model or number of reruns.
    matchers = record.get('matchers') or []
    if matchers:
        result = set()
        for row in matchers:
            name = handle(row.get('handle'))
            if name:
                result.add('@' + name)
            else:
                _family, model = attribution.model_claim(row.get('model'))
                result.add('project agents (' + model + ')')
        return result
    for item in (record, fn):
        name = handle(item.get('submitter'))
        if name:
            return {'@' + name}
    source = record.get('source', {}).get('compiled')
    path = root / source if source else None
    text = path.read_bytes()[:6000] if path and path.is_file() else None
    generated = {fn['id']} if record.get('origin') else set()
    _family, model, _basis = attribution.attribution(fn, record, generated, text)
    return {'project agents (' + model + ')'}


def tier(count):
    return next((name for minimum, name in ((1000, '1,000+'), (100, '100+'), (10, '10+'))
                 if count >= minimum), 'Contributor')


def standings(root, data):
    totals = defaultdict(lambda: dict(functions=0, bytes=0))
    seen = set()
    for fn in data['functions']:
        identity = fn['build_id'], fn['rva']
        if fn['status'] != 'matched' or identity in seen:
            continue
        seen.add(identity)
        record = json.loads((root / fn['report']).read_text())
        for name in credit(fn, record, root):
            totals[name]['functions'] += 1
            totals[name]['bytes'] += fn['size']
    return [dict(contributor=name, **counts, tier=tier(counts['functions']))
            for name, counts in sorted(totals.items(), key=lambda item:
                                       (-item[1]['functions'], -item[1]['bytes'], item[0]))]


NOTE = ('Current accepted functions only; revocations leave the leaderboard. Each contributor '
        'gets one credit per function, including independently verified alternate submissions, '
        'so contributor totals can exceed project totals. Bytes are the sum of function sizes, '
        'not unique executable coverage. Credit is a recorded claim, not proof of authorship. '
        'Project agents use the recorded Drafter model or generating tool; missing attribution '
        'is shown as Not reported. Tiers begin at 10, 100 and 1,000 functions. '
        'CI hash passes alone earn no accepted-match credit.')


def markdown(rows):
    lines = ['# Contributor leaderboard', '', NOTE, '',
             'Generated by `python3 tools/build_leaderboard.py` from `data/progress.json` and its accepted reports.',
             '', '[Report site](https://mudcrab-team.github.io/skyrim_decomp/leaderboard.html) · '
             '[Strike rules](docs/contributor-ci.md)', '',
             '| Contributor | Functions | Bytes | Tier |', '| --- | ---: | ---: | --- |']
    lines += [f'| {r["contributor"]} | {r["functions"]:,} | {r["bytes"]:,} | {r["tier"]} |' for r in rows]
    if not rows:
        lines += ['| No accepted contributions yet | 0 | 0 | — |']
    return '\n'.join(lines) + '\n'


def window_counts(root):
    """(functions open to claim, functions under open claims) from the published offered inventory, else None."""
    try:
        offered = json.loads((Path(root) / 'data/target-hashes/contributor-targets.json').read_text())
        return offered['next_candidate_count'], offered['claim_function_count']
    except (OSError, ValueError, KeyError):
        return None


def window_note(window):
    if not window:
        return ''
    return (f'<p>Open to claim: <strong>{window[0]:,}</strong> functions; under open claims: '
            f'<strong>{window[1]:,}</strong>. Counts as of the last refresh of the offered inventory.</p>')


def html(rows, window=None):
    body = ''.join(f'<tr><td>{escape(r["contributor"])}</td><td>{r["functions"]:,}</td>'
                   f'<td>{r["bytes"]:,}</td><td>{r["tier"]}</td></tr>' for r in rows)
    return ('<!doctype html><html lang="en"><meta charset="utf-8">'
            '<meta name="viewport" content="width=device-width,initial-scale=1">'
            '<title>Contributor leaderboard · Skyrim Research</title><link rel="stylesheet" href="style.css">'
            '<main><p><a href="index.html">Skyrim Research</a> / Contributors</p>'
            '<h1>Contributor leaderboard</h1><p>' + escape(NOTE) + '</p>' + window_note(window) +
            '<div style="overflow-x:auto"><table><thead><tr><th>Contributor</th><th>Functions</th>'
            '<th>Bytes</th><th>Tier</th></tr></thead><tbody>' + body + '</tbody></table></div></main></html>')


def public_records(root, rows):
    from contributor_standing import load, standing
    ledger = load(root)
    credit = {row['contributor'][1:]: row for row in rows if row['contributor'].startswith('@')}
    return dict(schema=1, contributors={name: dict(standing(ledger, name),
                verified_matches=credit.get(name, {}).get('functions', 0),
                matched_bytes=credit.get(name, {}).get('bytes', 0))
                for name in sorted(ledger['contributors'].keys() | credit.keys())})


def write(root, data):
    rows = standings(root, data)
    (root / 'LEADERBOARD.md').write_text(markdown(rows))
    (root / 'data/contributors.json').write_text(json.dumps(public_records(root, rows), indent=2) + '\n')
    return rows


def main():
    data = json.loads((ROOT / 'data/progress.json').read_text())
    rows = write(ROOT, data)
    print(f'Built LEADERBOARD.md; {len(rows)} contributor entries; accepted records only.')


if __name__ == '__main__':
    main()
