#!/usr/bin/env python3
"""Rank the matching-cookbook rules by how often they were used and how often they helped.

    python3 tools/cookbook_rank.py                 rewrite the ranking section of docs/matching-cookbook.md
    python3 tools/cookbook_rank.py --check         exit 1 when that section is out of date
    python3 tools/cookbook_rank.py --collect [PATH ...]
                                                   add hits recorded by drafters, then rewrite the section

Per rule, `fixed` is the number of distinct RVAs that either appear on the rule's `Evidence:` line
in the cookbook or are mapped to the rule in docs/cookbook-hits.json; `open` is the number of
distinct RVAs on its `Still failing:` line that are not already fixed by it. Rank is fixed + open
descending, then fixed descending, then rule number.

Drafters record a hit in one of two ways, and `--collect` merges both into docs/cookbook-hits.json:
the passing `tools/verifier/attempt ... --rule N[,M]` run writes `cookbook_rules` into the task's
attempts.jsonl (PATH is a tasks directory, a task directory or a worktree holding .local/tasks), and a
unit header line `// Cookbook: 0x<rva> N[, M]` (read from reconstruction/ under the repository). A hit
counts only for a function that data/progress.json lists as matched, so an attempt that was never
accepted adds nothing. The hits file only grows; nobody edits counts by hand.
"""
import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
COOKBOOK = Path('docs/matching-cookbook.md')
HITS = Path('docs/cookbook-hits.json')
PROGRESS = Path('data/progress.json')
BEGIN = '<!-- rank:begin -->'
END = '<!-- rank:end -->'
RVA = re.compile(r'0x[0-9a-fA-F]+')
RULE_HEAD = re.compile(r'\*\*(\d+)\. (.*)')
HEADER_HIT = re.compile(r'//[ \t]*Cookbook:[ \t]*(0x[0-9a-fA-F]+)[ \t]+(\d+(?:[ \t]*,[ \t]*\d+)*)[ \t]*$')
TITLE_WIDTH = 90


def norm(rva):
    return f'0x{int(rva, 16):x}'


def parse_rules(text):
    """{rule number: dict(title, evidence, failing)} from the numbered rules, in file order."""
    rules, current, title_open = {}, None, False
    for line in text.split('\n'):
        head = RULE_HEAD.match(line)
        if head:
            current = int(head.group(1))
            rules[current] = dict(title=head.group(2), evidence=set(), failing=set())
            title_open = '**' not in head.group(2)
            if not title_open:
                rules[current]['title'] = head.group(2).split('**')[0]
            continue
        if current is None:
            continue
        if line.startswith('## '):
            current = None
        elif title_open:
            before, _star, _after = line.partition('**')
            rules[current]['title'] += ' ' + before
            title_open = _star == ''
        elif line.startswith('Evidence:'):
            rules[current]['evidence'] |= {norm(r) for r in RVA.findall(line)}
        elif line.startswith('Still failing:'):
            rules[current]['failing'] |= {norm(r) for r in RVA.findall(line)}
    for rule in rules.values():
        title = ' '.join(rule['title'].split()).rstrip('.')
        rule['title'] = title if len(title) <= TITLE_WIDTH else title[:TITLE_WIDTH - 3].rstrip() + '...'
    return rules


def load_hits(root):
    path = Path(root) / HITS
    return json.loads(path.read_text()) if path.is_file() else {}


def save_hits(root, hits):
    ordered = {k: sorted(set(v)) for k, v in sorted(hits.items(), key=lambda kv: int(kv[0], 16))}
    (Path(root) / HITS).write_text(json.dumps(ordered, indent=1) + '\n')


def ranking(rules, hits):
    """[(rank, rule, title, fixed, open)] sorted by fixed + open, then fixed, then rule number."""
    rows = []
    for n, rule in rules.items():
        fixed = set(rule['evidence']) | {rva for rva, used in hits.items() if n in used}
        rows.append((n, rule['title'], len(fixed), len(rule['failing'] - fixed)))
    rows.sort(key=lambda r: (-(r[2] + r[3]), -r[2], r[0]))
    return [(i, *row) for i, row in enumerate(rows, 1)]


def section(rules, hits):
    lines = [BEGIN,
             '## Which rules matter most',
             '',
             'Generated by `tools/cookbook_rank.py`; do not edit by hand. **fixed** counts distinct functions a rule '
             'closed (cited on its `Evidence:` line or recorded when a drafter passed `--rule N`, '
             '`docs/cookbook-hits.json`); **open** counts distinct functions still failing on that cause '
             '(`Still failing:`). Ranked by fixed + open, then fixed.',
             '',
             '| Rank | Rule | Title | Fixed | Open |',
             '| ---: | ---: | --- | ---: | ---: |']
    for rank, n, title, fixed, open_ in ranking(rules, hits):
        lines.append(f'| {rank} | {n} | [{title.replace("|", "/")}](#rule-{n}) | {fixed} | {open_} |')
    lines.append(END)
    return '\n'.join(lines)


def rendered(text, hits):
    block = section(parse_rules(text), hits)
    if BEGIN in text and END in text:
        start = text.index(BEGIN)
        return text[:start] + block + text[text.index(END) + len(END):]
    anchor = text.index('## Control flow')
    return text[:anchor] + block + '\n\n' + text[anchor:]


def matched_rvas(root):
    data = json.loads((Path(root) / PROGRESS).read_text())
    return {f'0x{fn["rva"]:x}' for fn in data['functions'] if fn.get('status') == 'matched'}


def task_dirs(path):
    path = Path(path)
    for base in (path, path / '.local' / 'tasks'):
        if (base / 'task.json').is_file():
            return [base]
        found = sorted(p.parent for p in base.glob('*/task.json'))
        if found:
            return found
    return []


def attempt_hits(path):
    """{rva: {rules}} from passing attempts that carry `cookbook_rules`."""
    found = {}
    for task in task_dirs(path):
        try:
            rvas = [f'0x{fn["rva"]:x}' for fn in json.loads((task / 'task.json').read_text())['functions']]
            rows = [json.loads(line) for line in (task / 'attempts.jsonl').read_text().splitlines() if line.strip()]
        except (OSError, ValueError, KeyError, TypeError):
            continue
        for row in rows:
            if row.get('exit') == 0 and isinstance(row.get('cookbook_rules'), list):
                for rva in rvas:
                    found.setdefault(rva, set()).update(r for r in row['cookbook_rules'] if isinstance(r, int))
    return found


def header_hits(root):
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from lint_reconstruction import leading_comment
    found = {}
    for path in sorted((Path(root) / 'reconstruction').rglob('*')):
        if path.suffix not in ('.h', '.cpp') or not path.is_file():
            continue
        for line in leading_comment(path.read_text(encoding='utf-8', errors='replace')).split('\n'):
            hit = HEADER_HIT.fullmatch(line.strip())
            if hit:
                found.setdefault(norm(hit.group(1)), set()).update(int(n) for n in hit.group(2).split(','))
    return found


def collect(root, paths):
    known = set(parse_rules((Path(root) / COOKBOOK).read_text()))
    matched = matched_rvas(root)
    hits = {k: set(v) for k, v in load_hits(root).items()}
    new = [header_hits(root)] + [attempt_hits(p) for p in paths]
    added = 0
    for found in new:
        for rva, rules in found.items():
            useful = (rules & known) - hits.get(rva, set())
            if rva in matched and useful:
                hits.setdefault(rva, set()).update(useful)
                added += len(useful)
            elif rules - known:
                print(f'ignored unknown rule numbers {sorted(rules - known)} for {rva}', file=sys.stderr)
    save_hits(root, hits)
    return added


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--check', action='store_true', help='exit 1 when the ranking section is stale')
    p.add_argument('--collect', nargs='*', metavar='PATH', help='merge recorded hits first')
    p.add_argument('--repo', type=Path, default=ROOT)
    a = p.parse_args(argv)
    if a.collect is not None:
        print(f'{collect(a.repo, a.collect)} new hits')
    path = a.repo / COOKBOOK
    text = path.read_text()
    new = rendered(text, load_hits(a.repo))
    if a.check:
        if new != text:
            print('docs/matching-cookbook.md: the ranking section is out of date; run python3 tools/cookbook_rank.py')
            return 1
        return 0
    if new != text:
        path.write_text(new)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
